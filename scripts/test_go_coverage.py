#!/usr/bin/env python3
"""Regression checks for the workspace coverage gate."""

import subprocess
import sys
import tempfile
import unittest
from pathlib import Path


CHECKER = Path(__file__).with_name("check-go-coverage.py")


class CoverageGateTests(unittest.TestCase):
    def run_gate(self, modules):
        with tempfile.TemporaryDirectory(prefix="moox-coverage-test-") as temp:
            root = Path(temp)
            manifest = []
            for index, (covered, uncovered, generated) in enumerate(modules):
                module = f"module{index}"
                directory = root / module
                directory.mkdir()
                prefix = f"example.com/{module}"
                (directory / "go.mod").write_text(f"module {prefix}\n\ngo 1.25.0\n")
                (directory / "business.go").write_text("package business\n")
                # A package without tests must still lower overall coverage.
                (directory / "untested.go").write_text("package business\n")
                (directory / "generated.go").write_text(
                    "// Code generated by fixture. DO NOT EDIT.\npackage business\n"
                )
                profile = root / f"{index}.out"
                profile.write_text(
                    "mode: set\n"
                    f"{prefix}/business.go:2.1,2.2 {covered} 1\n"
                    f"{prefix}/untested.go:2.1,2.2 {uncovered} 0\n"
                    f"{prefix}/generated.go:3.1,3.2 {generated} 0\n"
                )
                manifest.append(f"{module}\t{profile}\n")
            manifest_path = root / "modules.tsv"
            manifest_path.write_text("".join(manifest))
            output = root / "coverage.out"
            result = subprocess.run(
                [sys.executable, str(CHECKER), str(root), str(manifest_path), str(output)],
                capture_output=True, text=True,
            )
            return result, output.read_text()

    def test_above_sixty_passes_and_generated_code_is_excluded(self):
        result, report = self.run_gate([(61, 39, 10000)])
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn("61.0000% (61/100 statements)", result.stdout)
        self.assertNotIn("generated.go", report)

    def test_exactly_sixty_fails(self):
        result, _ = self.run_gate([(60, 40, 0)])
        self.assertEqual(result.returncode, 1)
        self.assertIn("greater than 60%", result.stderr)

    def test_comparison_does_not_round_up_or_down(self):
        result, _ = self.run_gate([(600001, 399999, 0)])
        self.assertEqual(result.returncode, 0, result.stderr)
        result, _ = self.run_gate([(599999, 400001, 0)])
        self.assertEqual(result.returncode, 1)

    def test_modules_are_weighted_by_statements(self):
        result, _ = self.run_gate([(1, 0, 0), (59, 41, 0)])
        self.assertEqual(result.returncode, 1)
        self.assertIn("(60/101 statements)", result.stdout)

    def test_untested_code_is_included(self):
        result, report = self.run_gate([(1, 2, 0)])
        self.assertEqual(result.returncode, 1)
        self.assertIn("untested.go", report)

    def test_empty_or_generated_only_coverage_fails(self):
        for modules in ([], [(0, 0, 100)]):
            with self.subTest(modules=modules):
                result, _ = self.run_gate(modules)
                self.assertEqual(result.returncode, 1)
                self.assertIn("no non-generated statements", result.stderr)


if __name__ == "__main__":
    unittest.main()
