/**
 * 删除云账户的确认正文。后端是软删除、不检查引用：还在用它的执行器实例之后在管理台删不掉、
 * 不能部署和调用，云端函数也会留着，所以先查出在用的实例数写进正文。
 * inUse 为 null 表示没查到（查询失败），这时只写一般影响。
 */
export function cloudAccountDeleteText(inUse: number | null): string {
  if (inUse && inUse > 0) {
    return `还有 ${inUse} 个执行器实例在用这个云账户：删除后这些实例在管理台删不掉、不能部署和调用，云端函数会留着。请先删除这些实例。`;
  }
  if (inUse === 0) return "没有执行器实例在用这个云账户。";
  return "用这个云账户部署的执行器实例删除后在管理台删不掉、不能部署和调用，云端函数会留着。请先确认没有实例在用。";
}
